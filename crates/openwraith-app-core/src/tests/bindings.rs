#[test]
fn binding_shapes_match_the_conventions() {
    let dir = tempfile::tempdir().unwrap();
    export(&Config::new().with_out_dir(dir.path()));
    for entry in std::fs::read_dir(dir.path()).unwrap().flatten() {
        let text = std::fs::read_to_string(entry.path()).unwrap();
        let name = entry.file_name().to_string_lossy().into_owned();
        // No 64-bit numbers (they would be `bigint`), no optional fields
        // (every Option is serialised as null).
        assert!(!text.contains("bigint"), "{name}: bigint");
        assert!(!text.contains("?:"), "{name}: optional field");
    }
    // A sample of the serialised shapes.
    let status =
        serde_json::to_value(crate::dto::ConnectionState::Reading { done: 1, total: 2 }).unwrap();
    assert_eq!(
        status,
        serde_json::json!({"state": "reading", "done": 1, "total": 2})
    );
    let notice = serde_json::to_value(crate::dto::Notice::Connected).unwrap();
    assert_eq!(notice, serde_json::json!({"notice": "connected"}));
    let intent: crate::dto::RtIntent =
        serde_json::from_value(serde_json::json!({"mode": "separate", "press": 15, "release": 25}))
            .unwrap();
    assert_eq!(
        intent,
        crate::dto::RtIntent::Separate {
            press: 15,
            release: 25
        }
    );
    assert!(
        serde_json::from_value::<crate::dto::TriggerEditIntent>(serde_json::json!({
            "keys": [46], "actuation": 60, "rapid_trigger": null, "based_on": 1, "extra": 1
        }))
        .is_err(),
        "unknown fields are refused"
    );
    let token = serde_json::to_value(crate::dto::PlanToken("p-1".into())).unwrap();
    assert_eq!(token, serde_json::json!("p-1"));
}

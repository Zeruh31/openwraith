#[test]
fn bindings_are_up_to_date() {
    let dir = tempfile::tempdir().unwrap();
    let cfg = Config::new().with_out_dir(dir.path());
    export(&cfg);
    let mut files = BTreeMap::new();
    for entry in std::fs::read_dir(dir.path()).unwrap().flatten() {
        let name = entry.file_name().to_string_lossy().into_owned();
        let text = std::fs::read_to_string(entry.path())
            .unwrap()
            .replace("\r\n", "\n");
        files.insert(name, text);
    }
    assert!(files.len() > 80, "{} files", files.len());
    let mut index = String::from(
        "// This file was generated by the bindings test of openwraith-app-core. Do not edit this file manually.\n\n",
    );
    for name in files.keys() {
        let ty = name.trim_end_matches(".ts");
        index.push_str(&format!("export type {{ {ty} }} from \"./{ty}\";\n"));
    }
    files.insert("index.ts".to_string(), index);
    check_or_update(
        &repo_root().join("app/src/ipc/bindings"),
        "ts",
        &files,
        "UPDATE_BINDINGS",
        "UPDATE_BINDINGS=1 cargo test -p openwraith-app-core bindings",
    );
}

/// `app/src/generated/w75Keys.ts`.
fn w75_keys_ts() -> String {
    let mut text = String::from(
        "// This file was generated by the bindings test of openwraith-app-core from the\n\
         // protocol crate's W75 key table (docs/PROTOCOL.md section 5). Do not edit this file manually.\n\n\
         /** One key of the W75: matrix position and the library's key name. */\n\
         export interface W75Key {\n\
         \x20 /** Key index (row x 22 + col). */\n\
         \x20 readonly index: number;\n\
         \x20 readonly row: number;\n\
         \x20 readonly col: number;\n\
         \x20 /** The library's key name (\"W\", \"L-Shift\", \"Knob\"). */\n\
         \x20 readonly name: string;\n\
         \x20 /** The rotary knob: no trigger settings, never selectable. */\n\
         \x20 readonly knob: boolean;\n\
         \x20 /** The Fn key. */\n\
         \x20 readonly fn: boolean;\n\
         }\n\n\
         /** The 82 keys of the W75, in index order. */\n\
         export const W75_KEYS: readonly W75Key[] = [\n",
    );
    for key in W75.keys {
        text.push_str(&format!(
            "  {{ index: {}, row: {}, col: {}, name: {}, knob: {}, fn: {} }},\n",
            key.index,
            key.row,
            key.col,
            serde_json::to_string(key.name).unwrap(),
            W75.knob_index == Some(key.index),
            W75.fn_index == Some(key.index),
        ));
    }
    text.push_str("];\n");
    text
}

